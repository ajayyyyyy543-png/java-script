

var x = Number(prompt("Enter a number: "));

if (x >= 1 && x <= 12)
    console.log("GOOD MORNING");
else if (x >= 13 && x <= 17)
    console.log("GOOD AFTERNOON");
else if (x >= 18 && x <= 20)
    console.log("GOOD EVENING");
else if (x >= 21 && x <= 24)
    console.log("GOOD NIGHT");
else
    console.log("INVALID INPUT");
